import mongoose from "mongoose";
import { cartCollection, usersCollection } from "./index.js";

const userSchema = mongoose.Schema(
  {
    first_name: {
      type: String,
      required: true,
    },
    last_name: {
      type: String,
      required: true,
    },
    email: {
      type: String,
      required: true,
      unique: true,
    },
    password: {
      type: String,
      required: true,
    },
    age: Number,
    cart: {
      type: mongoose.Schema.Types.ObjectId,
      ref: cartCollection,
    },
    role: {
      type: String,
      enum: ["admin", "user"],
      default: "user",
      required: true,
    },
  },
  { timestamps: true }
);

const userModel = mongoose.model(usersCollection, userSchema);

export default userModel;
